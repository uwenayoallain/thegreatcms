/** `greatcms types` — TypeScript for the schema you already wrote. */

import { blockVariants, isBlocksRegion, type CmsSchema, type FieldDef } from "@greatcms/spec";
import { CliError } from "./ports.js";

export interface TypesOptions {
  /** Import specifier for the reader, so the augmentation targets the right module. */
  module?: string;
}

const PRINT_WIDTH = 100;

/**
 * Types for every region, block, and collection, plus a module augmentation so
 * `cms.region("home.hero")` is typed by its id rather than by a generic the
 * caller has to remember to pass.
 */
export function renderTypes(schema: CmsSchema, options: TypesOptions = {}): string {
  assertDistinctTypeNames(schema);
  const module = options.module ?? "@greatcms/reader";
  const out: string[] = [
    "// Generated by `greatcms types` from .cms/schema.yaml. Do not edit.",
    "//",
    "// Regenerate after changing the schema, and commit the result: it is the",
    "// only thing that makes a schema change show up as a type error rather",
    "// than as a blank space on the page.",
    "",
    'import type { RichText, CmsLink, CmsImage, CmsFile } from "@greatcms/reader";',
    "",
  ];

  const blockNames = Object.keys(schema.blocks).toSorted();
  for (const name of blockNames) {
    const block = schema.blocks[name];
    if (!block) continue;
    out.push(
      docComment(block.label, `Block \`${name}\`.`),
      `export interface ${blockTypeName(name)} {`,
      `  _type: ${JSON.stringify(name)};`,
      ...(blockVariants(block).length > 0
        ? [
            "  /** Which of the block's looks this one uses; the first when the content says nothing. */",
            `  _variant: ${blockVariants(block)
              .map((v) => JSON.stringify(v.value))
              .join(" | ")};`,
          ]
        : []),
      ...fieldLines(block.fields, schema),
      "}",
      "",
    );
  }

  if (blockNames.length > 0) {
    const names = blockNames.map(blockTypeName);
    const inline = `export type CmsBlock = ${names.join(" | ")};`;
    out.push(
      "/** Any block this schema defines, discriminated by `_type`. */",
      ...(inline.length <= PRINT_WIDTH
        ? [inline]
        : [
            "export type CmsBlock =",
            ...names.map((name, index) => `  | ${name}${index === names.length - 1 ? ";" : ""}`),
          ]),
      "",
    );
  }

  const regionIds = Object.keys(schema.regions).toSorted();
  for (const id of regionIds) {
    const region = schema.regions[id];
    if (!region) continue;

    if (isBlocksRegion(region)) {
      const allowed = region.allow.filter((name) => schema.blocks[name]);
      out.push(
        docComment(region.label, `Region \`${id}\` — a reorderable block list.`),
        `export interface ${regionTypeName(id)} {`,
        ...arrayUnionLines("  blocks: ", allowed.map(blockTypeName)),
        "}",
        "",
      );
      continue;
    }

    out.push(
      docComment(region.label, `Region \`${id}\`.`),
      `export interface ${regionTypeName(id)} {`,
      ...fieldLines(region.fields, schema),
      "}",
      "",
    );
  }

  const collectionNames = Object.keys(schema.collections).toSorted();
  for (const name of collectionNames) {
    const collection = schema.collections[name];
    if (!collection) continue;
    // A Markdown or MDX body is read back as the file's text, whatever type the field edits as.
    const body = collection.format === "json" ? undefined : collection.body;
    const bodyDef = body ? collection.fields[body] : undefined;
    const fields =
      body && bodyDef
        ? {
            ...collection.fields,
            [body]: {
              type: "text",
              required: true,
              label: bodyDef.label,
              description: bodyDef.description,
            } as FieldDef,
          }
        : collection.fields;
    out.push(
      docComment(collection.label, `Entry in collection \`${name}\`.`),
      `export interface ${entryTypeName(name)} {`,
      `  slug: string;`,
      `  file: string;`,
      `  body: string;`,
      "  data: {",
      ...fieldLines(fields, schema, "    "),
      "  };",
      "}",
      "",
    );
  }

  out.push(
    "/**",
    " * Teaches the reader this site's ids. With this in scope,",
    ' * `cms.region("home.hero")` is typed, and a typo is a compile error rather',
    " * than undefined at build time.",
    " */",
    `declare module ${JSON.stringify(module)} {`,
    "  interface GreatCMSRegions {",
    ...regionIds.map((id) => `    ${propertyName(id)}: ${regionTypeName(id)};`),
    "  }",
    "",
    "  interface GreatCMSCollections {",
    ...collectionNames.map((name) => `    ${propertyName(name)}: ${entryTypeName(name)};`),
    "  }",
    "}",
    "",
  );

  return out.join("\n");
}

function fieldLines(fields: Record<string, FieldDef>, schema: CmsSchema, indent = "  "): string[] {
  const lines: string[] = [];
  for (const name of Object.keys(fields).toSorted()) {
    const def = fields[name];
    if (!def) continue;
    // A field with a default always resolves to a value, so it is not optional
    // even when the content file omits it — that is what resolution guarantees.
    const optional = def.required || hasDefault(def) ? "" : "?";
    if (def.description) lines.push(`${indent}/** ${commentText(def.description)} */`);
    const prefix = `${indent}${propertyName(name)}${optional}: `;
    const type = typeOf(def, schema, indent);
    const line = `${prefix}${type};`;
    if (def.type === "blocks" && line.length > PRINT_WIDTH) {
      const allowed = def.allow.filter((blockName) => schema.blocks[blockName]);
      lines.push(...arrayUnionLines(prefix, allowed.map(blockTypeName)));
    } else {
      lines.push(line);
    }
  }
  return lines;
}

/** Matches oxfmt's two layouts for an Array whose union crosses the print width. */
function arrayUnionLines(prefix: string, names: string[]): string[] {
  const members = names.length > 0 ? names : ["CmsBlock"];
  const union = members.join(" | ");
  const inline = `${prefix}Array<${union}>;`;
  if (inline.length <= PRINT_WIDTH) return [inline];

  const indent = /^\s*/.exec(prefix)?.[0] ?? "";
  const unionLine = `${indent}  ${union}`;
  if (unionLine.length <= PRINT_WIDTH) {
    return [`${prefix}Array<`, unionLine, `${indent}>;`];
  }

  return [`${prefix}Array<`, ...members.map((member) => `${indent}  | ${member}`), `${indent}>;`];
}

function hasDefault(def: FieldDef): boolean {
  return "default" in def && def.default !== undefined;
}

function typeOf(def: FieldDef, schema: CmsSchema, indent: string): string {
  switch (def.type) {
    case "text":
    case "date":
      return "string";
    case "richtext":
      return "RichText";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "link":
      return "CmsLink";
    case "image":
      return "CmsImage";
    case "file":
      return "CmsFile";
    case "select": {
      const union = def.options
        .map((option) => JSON.stringify(typeof option === "string" ? option : option.value))
        .join(" | ");
      return def.multiple ? `Array<${union}>` : union;
    }
    case "list":
      return `Array<${typeOf(def.of, schema, indent)}>`;
    case "blocks": {
      const allowed = def.allow.filter((name) => schema.blocks[name]);
      return `Array<${allowed.length > 0 ? allowed.map(blockTypeName).join(" | ") : "CmsBlock"}>`;
    }
    case "group": {
      const inner = fieldLines(def.fields, schema, `${indent}  `);
      return `{\n${inner.join("\n")}\n${indent}}`;
    }
  }
}

/** `home.hero` → `HomeHero`, which is what a person would have named it. */
export function regionTypeName(id: string): string {
  return typeName(id, "Region");
}

export function blockTypeName(name: string): string {
  return typeName(name, "Block");
}

export function entryTypeName(name: string): string {
  return typeName(name, "Entry");
}

function typeName(name: string, suffix: string): string {
  const pascal = name
    .split(/[.\-_]/)
    .filter(Boolean)
    .map(capitalize)
    .join("");
  // `404` is a valid region id and not a valid identifier.
  return `${/^\d/.test(pascal) ? "_" : ""}${pascal}${suffix}`;
}

/** Names this file declares itself or imports, which no generated type may reuse. */
const RESERVED_NAMES = new Set(["CmsBlock", "RichText", "CmsLink", "CmsImage", "CmsFile"]);

/** Two schema names that become one type name would merge silently, so they are refused. */
function assertDistinctTypeNames(schema: CmsSchema): void {
  const seen = new Map<string, string>();
  const claim = (generated: string, source: string) => {
    const owner = RESERVED_NAMES.has(generated)
      ? "a type the generated file already uses"
      : seen.get(generated);
    if (owner) {
      throw new CliError(
        `${source} and ${owner} would both be named ${generated} in the generated types.`,
        "Rename one of them in .cms/schema.yaml.",
      );
    }
    seen.set(generated, source);
  };
  for (const name of Object.keys(schema.blocks)) claim(blockTypeName(name), `block \`${name}\``);
  for (const id of Object.keys(schema.regions)) claim(regionTypeName(id), `region \`${id}\``);
  for (const name of Object.keys(schema.collections))
    claim(entryTypeName(name), `collection \`${name}\``);
}

function capitalize(word: string): string {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

/** Quotes a key only when it is not a plain identifier. */
function propertyName(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function docComment(label: string | undefined, fallback: string): string {
  return `/** ${commentText(label ? `${label} — ${fallback}` : fallback)} */`;
}

/** A label containing `*\/` would close the comment and turn the rest into code. */
function commentText(text: string): string {
  return text.replaceAll("*/", "*\\/").replaceAll(/\r?\n/g, " ");
}
